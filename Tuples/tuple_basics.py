# Tuple 
# Definition:
# A tuple is an ordered, immutable(can't be changed) collection of items.
# Tuple allows duplicate values.

# Syntax:
# tuple_name=(item1,item2,item3)

# Empty tuple 
t=()
print(t)

# Single element tuple 
t=(10,)
print(t)

# Multiple element tuple
t=(10,15,30)
print(t)

# Using tuple
t=tuple([1,5,9])
print(t)

# Mixed elements tuple
t=(19,"savitha",39.4,'R')
print(t)
